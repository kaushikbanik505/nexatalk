const entries = FILES.map((relPath) => {
  const abs = path.join(repoRoot, relPath);
  const raw = fs.readFileSync(abs, "utf8").replace(/\r\n/g, "\n").replace(/\n$/, "");
  return `  ${JSON.stringify(relPath)}: ${JSON.stringify(raw)},`;
});

